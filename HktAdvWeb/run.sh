#!/usr/bin/env bash
# =====================================================================
# 원클릭 재현 — 설치 → 테스트 → 데모 서버 (step A1)
# 클린 클론에서 `bash run.sh` 한 번으로 재현되어야 한다 (불변 원칙 ⑤).
# =====================================================================
set -euo pipefail
cd "$(dirname "$0")"

echo "── npm install ──────────────────────────────────────────"
npm install --no-fund --no-audit

echo "── npm test ─────────────────────────────────────────────"
npm test

echo "── npm run demo ─────────────────────────────────────────"
echo "데모 서버를 띄운다. 브라우저에서 http://localhost:8173 확인 (Ctrl+C 로 종료)."
npm run demo
