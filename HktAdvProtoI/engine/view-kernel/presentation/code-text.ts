// 의미 코드 → 사람이 읽을 말 — **기반이 말을 짓지 않기 위한 자리** (문구 반전 ⑤).
//
// 기반은 무엇을 말해야 하는지를 코드로 부르고, 그 코드가 무슨 말이 되는지는 팩의
// 문구 표가 정한다. 명령 표면이 먼저 간 길이며(`command-presentation.ts`), 나머지
// 표면들도 같은 길을 쓴다 — 그래서 변환 함수의 형과 기본값이 여기 한 자리에 선다.
//
// 주지 않으면 코드가 그대로 보인다 — **표현 누락이 게임을 멈추지 않는다.**
// 조용히 그렇게 되는 것과 검사가 말해 주는 것은 다르므로, 기반이 부르는 코드의
// 목록을 `text-codes.ts` 가 모으고 팩의 검사가 덮이지 않은 것을 잡는다.
//
// 둘째 인자는 **문장에 끼워 넣을 값**이다 — 잰 수치, 친 낱말, 부르는 자리 표기.
// 값은 데이터이고 문장은 문구다. 어느 자리에 어떤 말로 끼우는지는 팩이 정한다
// (기반은 `{}` 가 어디에 있는지조차 알지 못한다).

export type CodeTextFn = (code: string, detail?: string) => string;

/** 팩이 말을 주지 않았을 때 — 코드를 그대로 보인다 */
export const RAW_CODE: CodeTextFn = (code, detail) =>
  detail === undefined ? code : `${code}: ${detail}`;
