//
// D 계층은 "무엇에 기대는가"(D0~D3)와 "지금 얼마나 비었는가"(D4)까지 세웠다. 압력은 목적의
// 씨앗이지만 아직 아무도 움직이지 않는다 — 무엇을 할 수 있는지가 없기 때문이다. P 계층이
// 잇는 것은 그 다음이다: **그 결핍 앞에 어떤 길이 놓이는가.**
//
// P0 는 그 길의 벽돌을 확정한다. 목록을 나열하는 일이 아니다 — 각 원자가 세계의 어느 자리를
// 바꾸겠다는 것이고(O2 9영역), 무엇을 치르며(O0 verifiable-cost), 어느 의존에 닿는지(D0 11종)를
// 못박는다. 그것이 P1 이 대응 방향을 펼칠 때 고르는 재료이고, P5 가 계획을 분해할 때 쓰는 단위이며,
// R2 규칙 엔진이 세계 변경 요청으로 받는 형식이다.
//
// 이 계층의 한 문장: **세계가 깊어지는 것은 행동을 늘려서가 아니라, 같은 행동이 놓인 자리가
// 달라서다.** 징수와 약탈은 같은 원자이고 갈리는 것은 그 뒤에 법이 서 있는가 하나뿐이다.
