// scenario — rule_0004 데모 세계. 원자는 *원자번호 Z 하나만* seed(질량 m 도 — 관성용). en·결합가는 코드가 창발.
//   네 무리를 떨어뜨려 각자 분자를 만든다: H₂O(공유) · NaCl(이온) · CO₂(이중결합 공유) · Ne 쌍(비활성).
//   굴리는 일은 엔진+규칙의 몫 — 시나리오는 초기 세계만 짠다.
const atom = (x, y, z, vx, vy, Z, m, hue) => ({ x, y, z, vx, vy, vz: 0, Z, m, hue, r: 2 + Math.sqrt(m) * 1.2 });

export default {
  rule: 'rule_0004',
  setup() {
    const W = 360, H = 360, D = 360;
    const els = [
      // H₂O — 산소(Z8) 양옆으로 수소(Z1) 둘이 천천히 접근 → 공유 결합(O 결합가 2 → H 둘만, 셋째는 안 받음)
      atom(90, 90, 180, 0, 0, 8, 16, 200),
      atom(78, 90, 180, 0.25, 0, 1, 1, 50),
      atom(102, 90, 180, -0.25, 0, 1, 1, 50),

      // NaCl — 나트륨(Z11, 금속)과 염소(Z17, 비금속) → 이온 결합(Na 가 전자 1 넘김), 전자기력에 묶임
      atom(260, 90, 180, 0.2, 0, 11, 23, 30),
      atom(285, 90, 180, -0.2, 0, 17, 35, 120),

      // CO₂ — 탄소(Z6, share, 결합가 4)에 산소(Z8) 둘이 이중결합(차수 2씩) → 정확히 CO₂ 에서 포화
      atom(90, 270, 180, 0.2, 0, 8, 16, 200),
      atom(110, 270, 180, 0, 0, 6, 12, 0),
      atom(130, 270, 180, -0.2, 0, 8, 16, 200),

      // Ne 쌍 — 네온(Z10, 꽉 찬 껍질) → 결합가 0 → 부딪쳐도 결합 안 함(주기적 비활성)
      atom(260, 270, 180, 0.3, 0, 10, 20, 300),
      atom(280, 270, 180, -0.3, 0, 10, 20, 300),
    ];
    return { width: W, height: H, depth: D, tick: 0, elements: els, impulses: [] };
  },
};
