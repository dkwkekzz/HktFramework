// scenario — 화학 쇼케이스: 전기음성도가 결합을 가르고, 전자기력이 끌고·민다.
//  ① H₂ (공유): en 같은 두 원자가 부드럽게 만남 → ΔEN=0 → 하나의 분자로 병합(중성, 1개체).
//  ② NaCl (이온): en 차이 큰 두 원자 → 전자 이동(Na⁺·Cl⁻) → 병합 대신 전자기력이 붙잡아
//     평형 거리에서 묶인 이온쌍이 됨(끌려와 과주행→Born 반발로 되튕김→마찰로 안착).
//  ③ 전자기 반발(튕김): 같은 부호(+,+) 이온쌍이 정면으로 다가옴 → 쿨롱 반발로 *감속·반전·튕김*.
//     (관성만이면 그냥 통과·등속일 텐데, 전자기력이 실제로 일함을 눈으로 본다.)
//  ④ 비활성 원자: 홀로 떠도는 중성 원자 — 짝이 없어 아무 일도 안 일어남.
// en·q 는 *시나리오가 seed* 하는 보편 스칼라(규칙은 차이만 읽음). Math.random 금지.
export default {
  rule: 'rule_0003',
  setup() {
    const w = 800, h = 600;
    const els = [];
    const atom = (x, y, vx, m, en, hue) => ({ x, y, z: 0, vx, vy: 0, m, en, q: 0, r: 2 + Math.sqrt(m) * 2, hue });
    const ion = (x, y, vx, m, en, q, hue) => ({ x, y, z: 0, vx, vy: 0, m, en, q, r: 2 + Math.sqrt(m) * 2, hue });

    // ① H₂ — en 2.2 동일 → 공유 결합(병합)
    els.push(atom(300, 120, +0.4, 1, 2.2, 50));
    els.push(atom(322, 120, -0.4, 1, 2.2, 50));

    // ② NaCl — Na(en 0.9) + Cl(en 3.2), ΔEN 2.3 → 이온 결합(전자 이동) → 전자기력이 묶음
    els.push(atom(250, 300, +0.4, 2, 0.9, 30));   // Na형(낮은 en)
    els.push(atom(296, 300, -0.4, 2, 3.2, 210));  // Cl형(높은 en)

    // ③ 전자기 반발 — 같은 부호(+1,+1) 이온쌍 정면 충돌 → 쿨롱 반발로 튕긴다(미리 이온화된 상태로 seed)
    els.push(ion(360, 470, +1.2, 2, 0.9, +1, 0));   // +이온
    els.push(ion(440, 470, -1.2, 2, 3.2, +1, 0));   // +이온 (둘 다 +면 서로 밀어 튕김)

    // ④ 비활성 원자 — 홀로, 짝 없음
    els.push(atom(640, 220, 0, 2, 2.5, 120));

    return { width: w, height: h, tick: 0, elements: els };
  },
};
