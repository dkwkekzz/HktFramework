// rule_0001 — 관성
//
// 세계의 첫 법칙: 원소는 *관성*을 갖는다 — 힘이 없으면 속도는 변하지 않고(등속), 위치만 v 로 적분된다.
//
// 이 적분(관성)·시간(tick)·토러스 랩은 세계 로직(engine.js)이 모든 원소에 *항상* 실현한다.
// 관성은 곧 '힘의 부재' 그 자체다 — 그러므로 rule_0001 은 원소에 *아무 힘도 더하지 않는다*(기여 0).
// 이것이 관성의 코드적 표현이다. 규칙이 늘면(rule_0002+) 그들이 힘을 누적하고, 엔진은 그대로다.
//
// 질량(m): 원소는 질량을 속성으로 가질 수 있으나, 자유 운동에서는 거동에 드러나지 않는다
//   (갈릴레이 — 같은 속도면 m 과 무관하게 같은 변위). 질량이 거동으로 드러나는 것은 *힘*이 작용할 때
//   (a = F/m)이며, 원소 간 힘을 더하는 rule_0002+ 의 몫이다. 엔진이 이미 a=F/m 를 소유한다.
//
// 보존: 자유 운동에서 총 운동량 Σ m·v 불변(힘이 없으니 변할 이유가 없다).

export default {
  id: 'rule_0001',
  name: '관성',
  defaults: { dt: 1 },

  // 관성 = 힘의 부재. 어떤 힘도 누적하지 않는다(적분·시간은 엔진의 몫).
  apply(e, i, world, params) {
    /* 기여 없음 — 관성은 힘이 0인 상태다. 자유 운동은 엔진의 적분이 실현한다. */
  },
};
